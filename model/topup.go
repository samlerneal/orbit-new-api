func Recharge(referenceId string, customerId string, callerIp string) (err error) {
	if referenceId == "" {
		return errors.New("未提供支付单号")
	}

	var quota float64
	topUp := &TopUp{}

	refCol := "`trade_no`"
	if common.UsingMainDatabase(common.DatabaseTypePostgreSQL) {
		refCol = `"trade_no"`
	}

	err = DB.Transaction(func(tx *gorm.DB) error {
		err := lockForUpdate(tx).Where(refCol+" = ?", referenceId).First(topUp).Error
		if err != nil {
			return errors.New("充值订单不存在")
		}

		if topUp.PaymentProvider != PaymentProviderStripe {
			return ErrPaymentMethodMismatch
		}

		if topUp.Status != common.TopUpStatusPending {
			return errors.New("充值订单状态错误")
		}

		topUp.CompleteTime = common.GetTimestamp()
		topUp.Status = common.TopUpStatusSuccess
		err = tx.Save(topUp).Error
		if err != nil {
			return err
		}

		quota = topUp.Money * common.QuotaPerUnit
		err = tx.Model(&User{}).Where("id = ?", topUp.UserId).Updates(map[string]interface{}{"stripe_customer": customerId, "quota": gorm.Expr("quota + ?", quota)}).Error
		if err != nil {
			return err
		}

		return nil
	})

	if err != nil {
		common.SysError("topup failed: " + err.Error())
		return errors.New("充值失败，请稍后重试")
	}

	RecordTopupLog(topUp.UserId, fmt.Sprintf("使用在线充值成功，充值金额: %v，支付金额：%d", logger.FormatQuota(int(quota)), topUp.Amount), callerIp, topUp.PaymentMethod, PaymentMethodStripe)

	return nil
}

// topUpQueryWindowSeconds 限制充值记录查询的时间窗口（秒）。
const topUpQueryWindowSeconds int64 = 30 * 24 * 60 * 60

// topUpQueryCutoff 返回允许查询的最早 create_time（秒级 Unix 时间戳）。
func topUpQueryCutoff() int64 {
	return common.GetTimestamp() - topUpQueryWindowSeconds
}

func GetUserTopUps(userId int, pageInfo *common.PageInfo) (topups []*TopUp, total int64, err error) {
	// Start transaction
	tx := DB.Begin()
	if tx.Error != nil {
		return nil, 0, tx.Error
	}
	defer func() {
		if r := recover(); r != nil {
			tx.Rollback()
		}
	}()

	cutoff := topUpQueryCutoff()

	// Get total count within transaction
	err = tx.Model(&TopUp{}).Where("user_id = ? AND create_time >= ?", userId, cutoff).Count(&total).Error
	if err != nil {
		tx.Rollback()
		return nil, 0, err
	}

	// Get paginated topups within same transaction
	err = tx.Where("user_id = ? AND create_time >= ?", userId, cutoff).Order("id desc").Limit(pageInfo.GetPageSize()).Offset(pageInfo.GetStartIdx()).Find(&topups).Error
	if err != nil {
		tx.Rollback()
		return nil, 0, err
	}

	// Commit transaction
	if err = tx.Commit().Error; err != nil {
		return nil, 0, err
	}

	redactLegacyUserTradeNos(topups, userId)
	return topups, total, nil
}

func redactLegacyUserTradeNos(topups []*TopUp, userID int) {
	for _, topup := range topups {
		if topup == nil {
			continue
		}
		legacyUser := fmt.Sprintf("USR%dNO", userID)
		legacyWaffo := fmt.Sprintf("WAFFO-%d-", userID)
		if strings.Contains(topup.TradeNo, legacyUser) || strings.Contains(topup.TradeNo, legacyWaffo) {
			topup.TradeNo = fmt.Sprintf("ORDER-%d", topup.Id)
		}
	}
}

func EnrichTopUpsWithBonusExpiry(topups []*TopUp) error {
	if len(topups) == 0 {
		return nil
	}
	topupIds := make([]int, 0, len(topups))
	byId := make(map[int]*TopUp, len(topups))
	for _, topup := range topups {
		if topup == nil {
			continue
		}
		topupIds = append(topupIds, topup.Id)
		byId[topup.Id] = topup
	}
	if len(topupIds) == 0 {
		return nil
	}
	type expiryRow struct {
		TopUpId   int
		ExpiresAt int64
	}
	var rows []expiryRow
	if err := DB.Model(&BonusBalance{}).
		Select("topup_id, MIN(expires_at) AS expires_at").
		Where("topup_id IN ?", topupIds).
		Group("topup_id").
		Scan(&rows).Error; err != nil {
		return err
	}
	for _, row := range rows {
		if topup := byId[row.TopUpId]; topup != nil {
			topup.BonusExpiresAt = row.ExpiresAt
		}
	}
	return nil
}

