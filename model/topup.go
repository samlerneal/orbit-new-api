const topUpCompletionLockCount = 256

var topUpCompletionLocks [topUpCompletionLockCount]sync.Mutex

func topUpCompletionLock(tradeNo string) *sync.Mutex {
	var hash uint32
	for index := 0; index < len(tradeNo); index++ {
		hash = hash*33 + uint32(tradeNo[index])
	}
	return &topUpCompletionLocks[hash%topUpCompletionLockCount]
}

func getTopUpCreditQuota(topUp *TopUp) int {
	if topUp.CreditQuota > 0 {
		return int(topUp.CreditQuota)
	}

	dAmount := decimal.NewFromInt(topUp.Amount)
	dQuotaPerUnit := decimal.NewFromFloat(common.QuotaPerUnit)
	return common.QuotaFromDecimal(dAmount.Mul(dQuotaPerUnit))
}

func CompleteEpayTopUp(
	tradeNo string,
	paymentMethod string,
	reportedMoney decimal.Decimal,
	callerIP string,
) error {
	if tradeNo == "" {
		return ErrTopUpNotFound
	}
	completionLock := topUpCompletionLock(tradeNo)
	completionLock.Lock()
	defer completionLock.Unlock()

	refCol := "`trade_no`"
	if common.UsingMainDatabase(common.DatabaseTypePostgreSQL) {
		refCol = `"trade_no"`
	}

	var completedTopUp TopUp
	var quotaToAdd int
	credited := false

	err := DB.Transaction(func(tx *gorm.DB) error {
		topUp := &TopUp{}
		if err := lockForUpdate(tx).Where(refCol+" = ?", tradeNo).First(topUp).Error; err != nil {
			return ErrTopUpNotFound
		}
		if topUp.PaymentProvider != PaymentProviderEpay || topUp.PaymentMethod != paymentMethod {
			return ErrPaymentMethodMismatch
		}

		expectedMoney := decimal.NewFromFloat(topUp.Money).Round(2)
		if !expectedMoney.Equal(reportedMoney.Round(2)) {
			return ErrPaymentAmountMismatch
		}
		if topUp.Status == common.TopUpStatusSuccess {
			return nil
		}
		if topUp.Status != common.TopUpStatusPending {
			return ErrTopUpStatusInvalid
		}

		quotaToAdd = getTopUpCreditQuota(topUp)
		if quotaToAdd <= 0 {
			return errors.New("invalid topup credit quota")
		}

		topUp.CompleteTime = common.GetTimestamp()
		topUp.Status = common.TopUpStatusSuccess
		bonusAwarded, err := applyCampaignAwardsTx(tx, topUp)
		if err != nil {
			return err
		}
		topUp.BonusCreditQuota = bonusAwarded
		if err := tx.Save(topUp).Error; err != nil {
			return err
		}
		if err := tx.Model(&User{}).Where("id = ?", topUp.UserId).Update("quota", gorm.Expr("quota + ?", quotaToAdd)).Error; err != nil {
			return err
		}

		completedTopUp = *topUp
		credited = true
		return nil
	})
	if err != nil {
		return err
	}
	if !credited {
		return nil
	}

	if err := cacheIncrUserQuota(completedTopUp.UserId, int64(quotaToAdd)); err != nil {
		common.SysLog("failed to increase user quota cache: " + err.Error())
	}
	RecordTopupLog(
		completedTopUp.UserId,
		fmt.Sprintf("使用在线充值成功，充值金额: %v，支付金额：%.2f", logger.LogQuota(quotaToAdd), completedTopUp.Money),
		callerIP,
		completedTopUp.PaymentMethod,
		PaymentProviderEpay,
	)
	return nil
}

